import type { OSProfile } from "./types";

export const READY_MARKER = "\u001b]777;simos-ready\u0007";

/**
 * Hooks the guest shell up to the studio. Written into the guest root filesystem before boot.
 *  - starts the shell in the project directory, which lives on the 9p root filesystem
 *  - applies terminal size changes from the studio at the next prompt
 */
function studioProfileScript(projectDir: string): string {
  return `# Generated by SimOs Studio. Safe to delete; it is re-created on every boot.
if [ -n "$PS1" ] && [ -z "$SIMOS_INIT" ]; then
  export SIMOS_INIT=1
  export PROJECT=${projectDir}
  bind 'set enable-bracketed-paste off' 2>/dev/null
  __simos_size() {
    local s
    [ -r /etc/simos-size ] || return 0
    read -r s < /etc/simos-size
    if [ "$s" != "$__simos_last" ]; then __simos_last=$s; stty $s 2>/dev/null; fi
  }
  PROMPT_COMMAND=__simos_size
  cd ${projectDir}
  printf '\\n\\033[2mSimOs Studio: this is a real Linux system. Your project is %s (shared with the editor).\\033[0m\\n\\n' "${projectDir}"
  printf '\\033]777;simos-ready\\007'
fi
`;
}

const PROJECT_DIR = "/root/project";
const KERNEL_CMDLINE = "loglevel=6 tsc=reliable mitigations=off random.trust_cpu=on console=ttyS0";

/**
 * Boot straight from the shared 9p filesystem. Pointing rdinit at a file that does not exist
 * makes the kernel skip its built-in initramfs and mount root= instead; `cache=mmap` turns off
 * the 9p read cache so edits made in the editor are visible in the guest immediately.
 */
const ALPINE_CMDLINE = [
  "rw root=host9p rootfstype=9p rootflags=trans=virtio,version=9p2000.L,cache=mmap",
  "rdinit=/nonexistent init=/sbin/init",
  KERNEL_CMDLINE,
].join(" ");

/**
 * Alpine Linux (musl, busybox, GNU bash, make, tcc, nano) on a Linux 6.8 kernel.
 * `base` is the URL prefix where scripts/build-rootfs.mjs put kernel.bin and alpine/ (served as <base>/alpine/fs.json).
 */
export function alpineProfile(base = "/os"): OSProfile {
  const b = base.replace(/\/$/, "");
  return {
    id: "alpine",
    name: "Alpine Linux",
    description: "Linux 6.8 with Alpine userland: GNU bash, busybox, make and a C compiler, on an x86 emulator.",
    memoryMB: 256,
    cmdline: ALPINE_CMDLINE,
    rootDir: "/",
    projectDir: PROJECT_DIR,
    assets: {
      bzimage: `${b}/kernel.bin`,
      rootfs: { manifest: `${b}/alpine/fs.json`, baseUrl: `${b}/alpine/blobs/` },
    },
    bootFiles: {
      "/etc/profile.d/10-simos.sh": { content: studioProfileScript(PROJECT_DIR), mode: 0o644 },
    },
    readyMarker: READY_MARKER,
  };
}

/** Minimal Buildroot Linux (busybox only), used by the fast automated tests. */
export function buildrootProfile(bzimageUrl: string): OSProfile {
  return {
    id: "buildroot",
    name: "Buildroot Linux",
    description: "Tiny Linux with busybox, for tests.",
    memoryMB: 128,
    cmdline: KERNEL_CMDLINE,
    rootDir: "/",
    projectDir: PROJECT_DIR,
    assets: { bzimage: bzimageUrl },
    bootFiles: {},
    readyMarker: "~% ",
  };
}

export const defaultProfile = alpineProfile();
